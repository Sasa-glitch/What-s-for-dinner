function populateIngredients(num) {
    var htmlMarkup = "";
    for (var i = 0; i < receipes[num].ingredients.length; i++) {
        htmlMarkup += `
        <li class="d-flex mb-3">
            <span class="flex-center rem-2-rec rounded-circle bg-local-primary me-2 fw-bold">${
                i + 1
            }</span>
            ${receipes[num].ingredients[i]}
        </li>
        `;
    }
    document.getElementsByClassName("ingredients-list")[0].innerHTML =
        htmlMarkup;
}

