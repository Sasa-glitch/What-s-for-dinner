var oldNum;
var theList = [];

function controlFlow() {
    do {
        var receNum = Math.floor(Math.random() * receipes.length);
    } while (receNum == oldNum || theList.includes(receNum));
    oldNum = receNum;
    theList.push(receNum)
    if (theList.length == receipes.length) {
        theList = [];
    }
    console.log(receNum);
    fillPicSide(receNum);
    fillBrief(receNum);
    populateIngredients(receNum);
    populateInstructions(receNum);
    populateNutrition(receNum);
    populateChefTips(receNum);
    window.scrollTo({ top: 100, left: 100, behavior: "smooth" });
}

